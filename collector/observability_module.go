func buildObservabilityMetrics() []serviceTimeseriesMetric {
	metrics := make([]serviceTimeseriesMetric, 0, len(observabilityMetricNames))
	for _, name := range observabilityMetricNames {
		metrics = append(metrics, serviceTimeseriesMetric{
			Name:  name,
			Help:  fmt.Sprintf("Cloudera observability metric %s.", name),
			Query: rawMetricQuery(name),
		})
	}
	return metrics
}

